package org.example.num5;

public class CalculadoraCientifica extends Calculadora{
    @Override
    Integer somar(Integer a, Integer b) {
        return super.somar(a, b);
    }
    //esse é sobrescrita
}
// Sobreescrita é quando se tem uma reescrita do método, onde diferentemente da sobrecarga o método é modificado mas mantém-se a mesma assinatura do método vindo da superclasse.


